// Demo conversations for the insurance-agents landing page.
//
// The flows mirror real, working Gambot botomations (renewal bots + a general agency bot) but are
// fully white-labelled: no agency name, insurer name, e-mail address or agent name from a real customer.
//
// Step grammar (kept tiny on purpose so the page can play it back as a chat):
//   { bot: "text" }                                  bot sends a message
//   { bot: "text", choices: [{ label, then: [...] }] } bot sends a message with quick-reply buttons
//   { bot: "text", ask: "sample answer", ai: true }  bot asks a free-text question (ai = AI validates the answer)
// Tokens {{key}} are replaced by the example values in `vars` and highlighted; *text* is bold.

const CLOSE_CHANGE = "קיבלנו, תודה.\nצוות הסוכנות יבחן את השינוי ויחזור אליך בהקדם עם הצעה מעודכנת ✨";
const CLOSE_PAYMENTS = "תודה! הפוליסה בטיפול.\nצוות הסוכנות ישלח אליך את הפוליסה החדשה 👌";
const CLOSE_QUESTION = "קיבלנו, מטפלים ונעדכן בהתאם.";

function confirmBranch(paymentQuestion, paymentSample, closing) {
  return [
    {
      bot: "מעולה. אפשר להתקדם עם חידוש הפוליסה?",
      choices: [
        {
          label: "מאשר",
          then: [
            { bot: paymentQuestion, ask: paymentSample, ai: true },
            { bot: closing || CLOSE_PAYMENTS },
          ],
        },
        {
          label: "יש לי שאלה",
          then: [
            { bot: "בכיף, מה השאלה?", ask: "האם אפשר להוסיף גם כיסוי לנזקי מים?" },
            { bot: CLOSE_QUESTION },
          ],
        },
      ],
    },
  ];
}

function changeChoice(label, question, sample, ai) {
  if (!question) return { label, then: [{ bot: CLOSE_CHANGE }] };
  return { label, then: [{ bot: question, ask: sample, ai: !!ai }, { bot: CLOSE_CHANGE }] };
}

